/** An icon by what it shows, in Orca's line weight and palette. */
export function Icon({ name, size = 18, tone = 'default', filled, testID }: IconProps) {
  const colors = useChatPalette();
  const color = {
    default: colors.textPrimary,
    muted: colors.textSecondary,
    accent: colors.accentBlue,
    danger: colors.statusRed,
    success: colors.statusGreen,
    warning: colors.statusAmber,
    onAccent: colors.bgBase,
  }[tone];
  const Glyph = ICONS[name];
  return <Glyph size={size} strokeWidth={2.1} color={color} {...(filled ? { fill: color } : {})} testID={testID} />;
}
