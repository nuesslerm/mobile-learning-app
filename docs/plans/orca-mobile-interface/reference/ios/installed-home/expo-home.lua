local function assertInk(point, label)
  local ink = device:get_pixel(point)
  assert(ink.r < 48 and ink.g < 48 and ink.b < 48, label)
end

sleep_ms(800)
device:take_screenshot(env.out .. "/expo-feed.png")
assertInk("38,885", "Feed tab is selected")
device:tap_on({point="30%,93.6%"})
sleep_ms(900)
device:take_screenshot(env.out .. "/expo-bots.png")
assertInk("127,889", "Bots tab is selected")
device:tap_on({point="10%,93.6%"})
sleep_ms(500)
device:tap_on({point="93%,8.9%"})
sleep_ms(1100)
device:take_screenshot(env.out .. "/expo-settings.png")
assertInk("200,89", "Settings title is centered below the status bar")
device:tap_on({point="7%,9.2%"})
sleep_ms(900)
device:take_screenshot(env.out .. "/expo-feed-return.png")
assertInk("38,885", "Back returned to Feed")
