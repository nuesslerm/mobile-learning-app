//! Renders the contract into each tool's native files. Output must stay byte-identical to the
//! TypeScript renderer, so key order follows JS object semantics (insertion order).
use crate::contract::{pick_slice, Contract, Permissions};
use crate::paths::{join, relative};
use crate::{Res, SHARED_SKILLS_DIR, SOURCES_PATH};
use regex::Regex;
use serde_json::{Map, Value};

pub struct Output {
    pub path: String,
    pub content: String,
    pub executable: bool,
}

fn out(path: String, content: String) -> Output {
    Output {
        path,
        content,
        executable: false,
    }
}

pub const LEGACY_PATHS: &[&str] = &[
    ".gemini",
    ".codex/commands",
    ".agents/worktrees",
    ".claude/tmp",
];
const CONFIG: &str = ".agents/config/*.json";

pub fn header(source: &str) -> String {
    format!("generated by agent-config-sync from {source}; edit that, then run pnpm run sync:agent-config")
}

fn json(v: &Value) -> String {
    format!(
        "{}\n",
        serde_json::to_string_pretty(v).expect("json serializes")
    )
}

fn vendored(c: &Contract) -> Vec<&crate::contract::Skill> {
    let prefix = format!("{SHARED_SKILLS_DIR}/");
    c.skills
        .iter()
        .filter(|s| !s.source.starts_with(&prefix))
        .collect()
}

pub fn owned_dirs(c: &Contract) -> Vec<String> {
    let mut dirs: Vec<String> = [
        ".claude/skills",
        ".claude/commands",
        ".claude/rules",
        ".opencode/commands",
    ]
    .iter()
    .map(|d| d.to_string())
    .collect();
    dirs.extend(
        vendored(c)
            .iter()
            .map(|s| join(&[SHARED_SKILLS_DIR, &s.name])),
    );
    dirs
}

fn with_project_dir(v: &Value, root: &str) -> Value {
    match v {
        Value::String(s) => Value::String(s.replace(root, "$CLAUDE_PROJECT_DIR")),
        Value::Array(a) => Value::Array(a.iter().map(|i| with_project_dir(i, root)).collect()),
        Value::Object(m) => Value::Object(
            m.iter()
                .map(|(k, v)| (k.clone(), with_project_dir(v, root)))
                .collect(),
        ),
        other => other.clone(),
    }
}

/* ---------- permissions ---------- */

fn strip_bash(item: &str) -> Option<&str> {
    if item.starts_with("Bash(") && item.ends_with(')') && item.len() >= 6 {
        Some(&item[5..item.len() - 1])
    } else {
        None
    }
}

fn strip_env_prefix(input: &str) -> String {
    Regex::new(r"^[A-Z_][A-Z0-9_]*=\S+\s+")
        .unwrap()
        .replace(input, "")
        .into_owned()
}

fn bash_tokens(stripped: &str) -> Vec<String> {
    let t = stripped.strip_suffix(":*").unwrap_or(stripped);
    t.split_whitespace().map(str::to_string).collect()
}

fn too_broad(tokens: &[String]) -> bool {
    tokens.len() <= 1
        && matches!(
            tokens.first().map(String::as_str).unwrap_or(""),
            "git" | "rm" | "mv" | "cp"
        )
}

fn parse_mcp_deny(item: &str) -> Option<(String, String)> {
    if !item.starts_with("mcp__") {
        return None;
    }
    let parts: Vec<&str> = item.split("__").collect();
    if parts.len() < 3 {
        return None;
    }
    Some((parts[1].to_string(), parts[2..].join("__")))
}

fn claude_permissions(p: &Permissions) -> Value {
    let mut deny: Vec<Value> = Vec::new();
    if p.claude.include_shared {
        deny.extend(p.shared_deny.iter().cloned().map(Value::String));
    }
    deny.extend(p.claude.deny.iter().cloned().map(Value::String));
    let mut m = Map::new();
    if let Some(mode) = p.claude.default_mode.as_ref().filter(|m| !m.is_empty()) {
        m.insert("defaultMode".into(), Value::String(mode.clone()));
    }
    m.insert("deny".into(), Value::Array(deny));
    m.insert(
        "allow".into(),
        Value::Array(p.claude.allow.iter().cloned().map(Value::String).collect()),
    );
    Value::Object(m)
}

fn opencode_permission(p: &Permissions) -> Value {
    let mut out = p.opencode.permission.clone();
    if !p.opencode.include_shared {
        return Value::Object(out);
    }
    for item in &p.shared_deny {
        if let Some((_, tool)) = parse_mcp_deny(item) {
            out.insert(format!("mcp_*_{tool}"), Value::String("deny".into()));
            continue;
        }
        if item.starts_with("Bash(") {
            let Some(stripped) = strip_bash(item) else {
                continue;
            };
            let stripped = strip_env_prefix(stripped);
            let pattern = match stripped.strip_suffix(":*") {
                Some(head) => format!("{head} *"),
                None => stripped.clone(),
            };
            let tokens = bash_tokens(&stripped);
            if tokens.is_empty() || too_broad(&tokens) {
                continue;
            }
            out.insert(format!("bash.{pattern}"), Value::String("deny".into()));
        }
    }
    Value::Object(out)
}

fn escape_toml(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn quote_toml(s: &str) -> String {
    format!("\"{}\"", escape_toml(s))
}

fn quote_key(key: &str) -> String {
    if !key.is_empty()
        && key
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    {
        key.to_string()
    } else {
        quote_toml(key)
    }
}

fn toml_scalar(v: &Value) -> String {
    match v {
        Value::String(s) => quote_toml(s),
        Value::Number(n) => n.to_string(),
        Value::Bool(b) => b.to_string(),
        Value::Array(a) => format!(
            "[{}]",
            a.iter().map(toml_scalar).collect::<Vec<_>>().join(", ")
        ),
        Value::Object(m) => format!(
            "{{ {} }}",
            m.iter()
                .map(|(k, v)| format!("{} = {}", quote_key(k), toml_scalar(v)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Value::Null => "null".to_string(),
    }
}

struct CodexPerms {
    top_level: String,
    tables: String,
    rules_file: String,
}

fn codex_permissions(p: &Permissions) -> CodexPerms {
    let mut top: Vec<String> = Vec::new();
    if !p.codex.approval_policy.is_empty() {
        top.push(format!("approval_policy = \"{}\"", p.codex.approval_policy));
    }
    if !p.codex.default_permissions.is_empty() {
        top.push(format!(
            "default_permissions = \"{}\"",
            p.codex.default_permissions
        ));
    }

    let mut tables: Vec<String> = Vec::new();
    if !p.codex.permissions.is_empty() {
        tables.push("[permissions.project]".into());
        let project = p
            .codex
            .permissions
            .get("project")
            .and_then(Value::as_object);
        if let Some(fs) = project
            .and_then(|pr| pr.get("filesystem"))
            .and_then(Value::as_object)
        {
            tables.push(String::new());
            tables.push("[permissions.project.filesystem]".into());
            for (k, v) in fs {
                tables.push(format!("{} = {}", quote_key(k), toml_scalar(v)));
            }
        }
        if let Some(net) = project
            .and_then(|pr| pr.get("network"))
            .and_then(Value::as_object)
        {
            tables.push(String::new());
            tables.push("[permissions.project.network]".into());
            for (k, v) in net {
                tables.push(format!("{k} = {}", toml_scalar(v)));
            }
        }
    }

    let mut rules: Vec<String> = Vec::new();
    if p.codex.include_shared {
        for item in &p.shared_deny {
            if item.starts_with("Bash(") {
                let Some(stripped) = strip_bash(item) else {
                    continue;
                };
                let tokens = bash_tokens(&strip_env_prefix(stripped));
                if tokens.is_empty() {
                    continue;
                }
                if too_broad(&tokens) {
                    rules.push(format!("# codex: skipped over-broad shared deny: {item}"));
                    continue;
                }
                rules.push("prefix_rule(".into());
                rules.push(format!(
                    "    pattern = [{}],",
                    tokens
                        .iter()
                        .map(|t| quote_toml(t))
                        .collect::<Vec<_>>()
                        .join(", ")
                ));
                rules.push("    decision = \"forbidden\",".into());
                rules.push("    justification = \"Denied by project permissions policy\",".into());
                rules.push(")".into());
                rules.push(String::new());
            } else if item.starts_with("mcp__") {
                rules.push(format!(
                    "# codex: no direct MCP tool deny support; skipped: {item}"
                ));
            }
        }
    }
    for extra in &p.codex.rules {
        rules.push(extra.clone());
        if !extra.ends_with('\n') {
            rules.push(String::new());
        }
    }
    CodexPerms {
        top_level: top.join("\n"),
        tables: tables.join("\n"),
        rules_file: rules.join("\n"),
    }
}

/* ---------- mcp targets ---------- */

fn collect_slices(c: &Contract, tool: &str) -> Map<String, Value> {
    let mut out = Map::new();
    for name in c.mcps.keys() {
        if let Some(slice) = pick_slice(&c.mcps, name, tool) {
            out.insert(name.clone(), Value::Object(slice.clone()));
        }
    }
    out
}

fn normalize_claude_config(cfg: &Map<String, Value>) -> Value {
    let mut out = Map::new();
    for (k, v) in cfg {
        if k == "enabled" {
            continue;
        }
        if k == "type" {
            let t = if v.as_str() == Some("local") {
                Value::String("stdio".into())
            } else {
                v.clone()
            };
            out.insert("type".into(), t);
            continue;
        }
        if k == "command" {
            if let Some(arr) = v.as_array().filter(|a| !a.is_empty()) {
                out.insert("command".into(), arr[0].clone());
                if arr.len() > 1 && !cfg.contains_key("args") {
                    out.insert("args".into(), Value::Array(arr[1..].to_vec()));
                }
                continue;
            }
        }
        out.insert(k.clone(), v.clone());
    }
    Value::Object(out)
}

fn render_claude_mcp(c: &Contract) -> Value {
    let servers: Map<String, Value> = collect_slices(c, "claude")
        .into_iter()
        .map(|(name, cfg)| {
            (
                name,
                normalize_claude_config(cfg.as_object().expect("slice is an object")),
            )
        })
        .collect();
    let mut m = Map::new();
    m.insert("mcpServers".into(), Value::Object(servers));
    Value::Object(m)
}

/// JS `String(v)` for the scalar and container values an MCP config can hold.
fn js_string(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Null => "null".into(),
        Value::Array(a) => a.iter().map(js_string).collect::<Vec<_>>().join(","),
        Value::Object(_) => "[object Object]".into(),
        other => other.to_string(),
    }
}

fn toml_string_array(a: &[Value]) -> Res<String> {
    let items = a
        .iter()
        .map(|i| {
            i.as_str()
                .map(quote_toml)
                .ok_or_else(|| "codex MCP arrays must hold strings".to_string())
        })
        .collect::<Res<Vec<_>>>()?;
    Ok(format!("[{}]", items.join(", ")))
}

fn render_codex_mcp(c: &Contract) -> Res<String> {
    let mut lines: Vec<String> = Vec::new();
    for (name, cfg) in collect_slices(c, "codex") {
        let cfg = cfg.as_object().expect("slice is an object");
        let mut table: Map<String, Value> = Map::new();
        let mut env: Option<Map<String, Value>> = None;
        for (k, v) in cfg {
            if k == "env" && v.is_object() {
                env = Some(
                    v.as_object()
                        .unwrap()
                        .iter()
                        .map(|(ek, ev)| (ek.clone(), Value::String(js_string(ev))))
                        .collect(),
                );
                continue;
            }
            if k == "command" {
                match v {
                    Value::String(s) => {
                        table.insert("command".into(), Value::String(s.clone()));
                    }
                    Value::Array(a) if !a.is_empty() => {
                        table.insert("command".into(), a[0].clone());
                        if a.len() > 1 {
                            table.insert("args".into(), Value::Array(a[1..].to_vec()));
                        }
                    }
                    _ => {}
                }
                continue;
            }
            if k == "args" && v.is_array() {
                table.insert("args".into(), v.clone());
                continue;
            }
            match v {
                Value::Null => {}
                Value::String(_) | Value::Number(_) | Value::Bool(_) => {
                    table.insert(k.clone(), Value::String(js_string(v)));
                }
                Value::Array(_) => {
                    table.insert(k.clone(), v.clone());
                }
                Value::Object(_) => {}
            }
        }
        lines.push(format!("[mcp_servers.{name}]"));
        for (k, v) in &table {
            let rendered = match v {
                Value::String(s) => quote_toml(s),
                Value::Array(a) => toml_string_array(a)?,
                other => other.to_string(),
            };
            lines.push(format!("{k} = {rendered}"));
        }
        if let Some(env) = env.filter(|e| !e.is_empty()) {
            let entries: Vec<String> = env
                .iter()
                .map(|(k, v)| format!("{k} = {}", quote_toml(v.as_str().unwrap_or(""))))
                .collect();
            lines.push(format!("env = {{ {} }}", entries.join(", ")));
        }
        lines.push(String::new());
    }
    Ok(lines.join("\n"))
}

/* ---------- per tool ---------- */

fn instructions(c: &Contract) -> Vec<Output> {
    c.instructions
        .iter()
        .flat_map(|i| {
            ["AGENTS.md", "CLAUDE.md"].map(|file| {
                out(
                    join(&[&i.dir, file]),
                    format!("<!-- {} -->\n\n{}", header(&i.source), i.body),
                )
            })
        })
        .collect()
}

fn claude(c: &Contract, root: &str, existing: &Map<String, Value>) -> Vec<Output> {
    let mut settings = existing.clone();
    settings.shift_remove("permissions");
    settings.shift_remove("hooks");
    for key in ["outputStyle", "effortLevel", "env"] {
        settings.shift_remove(key);
    }
    for (k, v) in &c.claude_settings {
        settings.insert(k.clone(), v.clone());
    }
    settings.insert("permissions".into(), claude_permissions(&c.permissions));
    settings.insert(
        "hooks".into(),
        with_project_dir(&Value::Object(c.hooks_claude.clone()), root),
    );

    let mut outputs = vec![
        out(".claude/settings.json".into(), json(&Value::Object(settings))),
        out(".mcp.json".into(), json(&render_claude_mcp(c))),
        Output {
            path: ".claude/setup.sh".into(),
            executable: true,
            content: format!(
                "#!/usr/bin/env bash\n# {}\nexec bash \"$(dirname -- \"${{BASH_SOURCE[0]}}\")/{}\" \"$@\"\n",
                header(SOURCES_PATH),
                relative(".claude", &c.setup)
            ),
        },
    ];
    outputs.extend(c.commands.iter().map(|cmd| {
        out(
            format!(".claude/commands/{}.md", cmd.name),
            cmd.body.clone(),
        )
    }));
    outputs.extend(
        c.rules
            .iter()
            .map(|r| out(format!(".claude/rules/{}.md", r.name), r.body.clone())),
    );
    for s in &c.skills {
        for (rel, content) in &s.files {
            outputs.push(out(
                join(&[".claude/skills", &s.name, rel]),
                content.clone(),
            ));
        }
    }
    outputs
}

fn codex(c: &Contract) -> Res<Vec<Output>> {
    let perms = codex_permissions(&c.permissions);
    let config = [
        format!("# {}\n{}", header(CONFIG), perms.top_level),
        render_codex_mcp(c)?,
        perms.tables,
    ]
    .iter()
    .map(|p| p.trim().to_string())
    .filter(|p| !p.is_empty())
    .collect::<Vec<_>>()
    .join("\n\n");
    validate_toml(&config, ".codex/config.toml")?;
    let mut hooks = Map::new();
    hooks.insert("hooks".into(), Value::Object(c.hooks_codex.clone()));
    let rules = if perms.rules_file.is_empty() {
        String::new()
    } else {
        format!("{}\n", perms.rules_file)
    };
    let mut outputs = vec![
        out(".codex/config.toml".into(), format!("{config}\n")),
        out(".codex/hooks.json".into(), json(&Value::Object(hooks))),
        out(
            ".codex/execpolicy/project.rules".into(),
            format!("# {}\n{rules}", header(CONFIG)),
        ),
    ];
    for s in vendored(c) {
        for (rel, content) in &s.files {
            outputs.push(out(
                join(&[SHARED_SKILLS_DIR, &s.name, rel]),
                content.clone(),
            ));
        }
    }
    Ok(outputs)
}

fn validate_toml(raw: &str, path: &str) -> Res<()> {
    if raw.trim().is_empty() {
        return Err(format!("{path}: file is empty at {path}"));
    }
    raw.parse::<toml::Table>()
        .map(|_| ())
        .map_err(|e| format!("{path}: invalid TOML at {path}: {e}"))
}

fn opencode(c: &Contract) -> Vec<Output> {
    let mut config = Map::new();
    config.insert(
        "$schema".into(),
        Value::String("https://opencode.ai/config.json".into()),
    );
    config.insert("mcp".into(), Value::Object(collect_slices(c, "opencode")));
    config.insert("permission".into(), opencode_permission(&c.permissions));
    config.insert("plugin".into(), Value::Array(c.plugins_opencode.clone()));
    if !c.rules.is_empty() {
        config.insert(
            "instructions".into(),
            Value::Array(
                c.rules
                    .iter()
                    .map(|r| Value::String(r.source.clone()))
                    .collect(),
            ),
        );
    }
    let mut hooks = Map::new();
    hooks.insert("hooks".into(), Value::Object(c.hooks_opencode.clone()));
    let mut outputs = vec![
        out("opencode.json".into(), json(&Value::Object(config))),
        out(".opencode/hooks.json".into(), json(&Value::Object(hooks))),
    ];
    outputs.extend(c.commands.iter().map(|cmd| {
        out(
            format!(".opencode/commands/{}.md", cmd.name),
            cmd.body.clone(),
        )
    }));
    outputs
}

/// Every generated file in the TypeScript order: shared, claude, codex, opencode.
pub fn render_outputs(
    c: &Contract,
    root: &str,
    existing_claude_settings: &Map<String, Value>,
) -> Res<Vec<Output>> {
    let mut all = instructions(c);
    all.extend(claude(c, root, existing_claude_settings));
    all.extend(codex(c)?);
    all.extend(opencode(c));
    Ok(all)
}
