//! `wf mimic crawl`: the endpoint inventory and request corpus of a pinned reference, and the completeness guard over them.
//!
//! A `Crawler` port reads the reference's own source (a driver on Node for the TypeScript references) and answers one
//! `mimic-crawl-report/1`: every endpoint with who uses it and where it was seen, and the cases (valid, boundary and invalid inputs) derived
//! from each payload schema. This module checks that report against the committed catalog of the pinned source (what `wf parity coverage`
//! lists), merges it into three files (`inventory.json`, `corpus.json`, `coverage.json`) and re-checks the committed ones offline: a corpus
//! cannot lag the reference silently. No I/O; the file layout and the child process are the thin crate's.
use crate::corpus::{CaseSpec, CorpusSpec, GeneratorSpec, SCHEMA as CORPUS_SCHEMA};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::collections::{BTreeMap, BTreeSet};

pub const REPORT_SCHEMA: &str = "mimic-crawl-report/1";
pub const INVENTORY_SCHEMA: &str = "mimic-inventory/1";
pub const COVERAGE_SCHEMA: &str = "mimic-coverage/1";
/// The input classes a schema-derived endpoint must have at least one case of.
pub const SCHEMA_CLASSES: [&str; 2] = ["valid", "invalid"];

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Pin {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub version: Option<String>,
    pub commit: String,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct SourceNote {
    pub name: String,
    pub available: bool,
    pub found: usize,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Endpoint {
    pub id: String,
    pub kind: String,
    pub name: String,
    pub transport: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub method: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    pub streaming: bool,
    pub users: Vec<String>,
    pub sources: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub access: Option<String>,
    pub input: String,
    #[serde(default)]
    pub classes: BTreeMap<String, usize>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub skipped: Option<String>,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct CliCommand {
    pub path: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub summary: Option<String>,
    pub source: String,
}

/// An endpoint class the crawler cannot see, and the source that would show it.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Blind {
    pub class: String,
    pub missing_source: String,
    pub detail: String,
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Report {
    pub schema: String,
    pub app: String,
    pub pin: Pin,
    pub sources: Vec<SourceNote>,
    pub endpoints: Vec<Endpoint>,
    #[serde(default)]
    pub cli_commands: Vec<CliCommand>,
    pub cases: Vec<CaseSpec>,
    #[serde(default)]
    pub blind: Vec<Blind>,
}

#[derive(Clone, Debug, PartialEq)]
pub struct CrawlError(pub String);

impl std::fmt::Display for CrawlError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "crawl failed: {}", self.0)
    }
}

impl std::error::Error for CrawlError {}

/// Reads the reference's source and reports what it defines.
pub trait Crawler {
    fn crawl(&mut self) -> Result<Report, CrawlError>;
}

/// The row ids of the pinned source as the committed catalog lists them (`<app>-methods.json`, generated by `wf parity coverage`).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Catalog {
    pub ids: BTreeSet<String>,
}

impl Catalog {
    pub fn parse(text: &str) -> Result<Self, String> {
        let v: Value = serde_json::from_str(text).map_err(|e| format!("the catalog is not JSON: {e}"))?;
        let rows = v.get("rows").and_then(Value::as_array).ok_or("the catalog has no rows")?;
        let ids = rows.iter().filter_map(|r| r.get("id").and_then(Value::as_str).map(String::from)).collect();
        Ok(Self { ids })
    }
}

#[derive(Serialize, Clone, Debug, PartialEq)]
pub struct Problem {
    pub code: &'static str,
    pub id: String,
    pub detail: String,
}

fn problem(code: &'static str, id: impl Into<String>, detail: impl Into<String>) -> Problem {
    Problem { code, id: id.into(), detail: detail.into() }
}

fn tag_class(tags: &[String]) -> Option<&str> {
    tags.iter().find_map(|t| t.strip_prefix("class:"))
}

/// Cases per row and input class, counted from the cases themselves (what the endpoint claims is not trusted).
pub fn class_counts(cases: &[CaseSpec]) -> BTreeMap<String, BTreeMap<String, usize>> {
    let mut out: BTreeMap<String, BTreeMap<String, usize>> = BTreeMap::new();
    for c in cases {
        let row = c.row.clone().unwrap_or_default();
        *out.entry(row).or_default().entry(tag_class(&c.tags).unwrap_or("unclassified").to_string()).or_default() += 1;
    }
    out
}

/// The completeness guard. `catalog` is the pinned source as the committed catalog lists it; `pin_commit` the commit the pin file names now.
/// Problems fail the crawl; `warnings` name what is merely worth a look (an endpoint the catalog does not list).
pub fn check(report: &Report, catalog: Option<&Catalog>, pin_commit: Option<&str>) -> (Vec<Problem>, Vec<String>) {
    let mut problems = Vec::new();
    let mut warnings = Vec::new();
    if report.schema != REPORT_SCHEMA {
        problems.push(problem("schema", &report.app, format!("the report is {}, this build reads {REPORT_SCHEMA}", report.schema)));
    }
    if let Some(now) = pin_commit {
        if now != report.pin.commit {
            problems.push(problem("stale-pin", &report.pin.commit, format!("the crawl was made at {}, the pin file names {now}: crawl again", report.pin.commit)));
        }
    }
    let ids: BTreeSet<&str> = report.endpoints.iter().map(|e| e.id.as_str()).collect();
    if ids.len() != report.endpoints.len() {
        let mut seen = BTreeSet::new();
        for e in &report.endpoints {
            if !seen.insert(e.id.as_str()) {
                problems.push(problem("duplicate-endpoint", &e.id, "two endpoints share an id"));
            }
        }
    }
    match catalog {
        Some(cat) => {
            for id in cat.ids.iter().filter(|id| !ids.contains(id.as_str())) {
                problems.push(problem("lags-source", id, "the pinned source defines it (the catalog lists it) and the crawl does not: the crawler misses a kind of definition"));
            }
            for id in ids.iter().filter(|id| !cat.ids.contains(**id)) {
                warnings.push(format!("{id}: found by the crawl, not listed by the catalog (regenerate it with wf parity coverage, or the crawl over-reads)"));
            }
        }
        None => warnings.push("no catalog: the crawl was not compared with the pinned source's own listing".into()),
    }
    let counts = class_counts(&report.cases);
    let mut case_ids = BTreeSet::new();
    for c in &report.cases {
        if !case_ids.insert(c.id.as_str()) {
            problems.push(problem("duplicate-case", &c.id, "two cases share an id"));
        }
        match c.row.as_deref() {
            Some(row) if ids.contains(row) => {}
            other => problems.push(problem("orphan-case", &c.id, format!("its row {other:?} is not an endpoint of the inventory"))),
        }
    }
    for e in &report.endpoints {
        if e.users.is_empty() {
            problems.push(problem("no-user", &e.id, "it names no user (mobile, cli or internal)"));
        }
        let per = counts.get(&e.id).cloned().unwrap_or_default();
        let total: usize = per.values().sum();
        match &e.skipped {
            Some(reason) if reason.trim().is_empty() => problems.push(problem("skip-without-reason", &e.id, "a skipped endpoint needs the reason it cannot be recorded")),
            Some(_) if total > 0 => problems.push(problem("skipped-with-cases", &e.id, format!("it is skipped and has {total} case(s)"))),
            Some(_) => {}
            None if total == 0 => problems.push(problem("uncovered", &e.id, "no case asks it and it is not skipped: the corpus lags the inventory")),
            None => {
                if e.classes != per {
                    problems.push(problem("classes-disagree", &e.id, format!("the inventory says {:?}, the cases are {per:?}", e.classes)));
                }
                if e.input != "empty" {
                    for class in SCHEMA_CLASSES {
                        if !per.contains_key(class) {
                            problems.push(problem("missing-class", &e.id, format!("its input is {}-derived and it has no {class} case", e.input)));
                        }
                    }
                }
            }
        }
    }
    (problems, warnings)
}

#[derive(Serialize, Debug, PartialEq)]
pub struct Summary {
    pub app: String,
    pub pin: Pin,
    pub endpoints: usize,
    pub by_kind: BTreeMap<String, usize>,
    pub by_user: BTreeMap<String, usize>,
    pub by_source: BTreeMap<String, usize>,
    pub by_input: BTreeMap<String, usize>,
    pub by_class: BTreeMap<String, usize>,
    pub cases: usize,
    pub skipped: usize,
    pub streaming: usize,
    pub cli_commands: usize,
    pub sources: Vec<SourceNote>,
    pub blind: Vec<Blind>,
}

pub fn summary(report: &Report) -> Summary {
    let by = |f: &dyn Fn(&Endpoint) -> Vec<String>| {
        let mut m: BTreeMap<String, usize> = BTreeMap::new();
        for e in &report.endpoints {
            for k in f(e) {
                *m.entry(k).or_default() += 1;
            }
        }
        m
    };
    let mut by_class: BTreeMap<String, usize> = BTreeMap::new();
    for c in &report.cases {
        *by_class.entry(tag_class(&c.tags).unwrap_or("unclassified").to_string()).or_default() += 1;
    }
    Summary {
        app: report.app.clone(),
        pin: report.pin.clone(),
        endpoints: report.endpoints.len(),
        by_kind: by(&|e| vec![e.kind.clone()]),
        by_user: by(&|e| e.users.clone()),
        by_source: by(&|e| e.sources.clone()),
        by_input: by(&|e| vec![e.input.clone()]),
        by_class,
        cases: report.cases.len(),
        skipped: report.endpoints.iter().filter(|e| e.skipped.is_some()).count(),
        streaming: report.endpoints.iter().filter(|e| e.streaming).count(),
        cli_commands: report.cli_commands.len(),
        sources: report.sources.clone(),
        blind: report.blind.clone(),
    }
}

/// The three files a crawl writes, as text: the order of everything is the report's, so equal reports give equal bytes.
#[derive(Clone, Debug, PartialEq)]
pub struct Outputs {
    pub inventory: String,
    pub corpus: String,
    pub coverage: String,
}

fn pretty(v: &Value) -> String {
    serde_json::to_string_pretty(v).expect("a value prints") + "\n"
}

pub fn inventory(report: &Report) -> Value {
    json!({
        "schema": INVENTORY_SCHEMA, "app": report.app, "pin": report.pin, "sources": report.sources, "endpoints": report.endpoints,
        "cli_commands": report.cli_commands, "blind": report.blind, "counts": summary(report),
    })
}

pub fn coverage(report: &Report) -> Value {
    let counts = class_counts(&report.cases);
    let rows: Vec<Value> = report
        .endpoints
        .iter()
        .map(|e| match &e.skipped {
            Some(reason) => json!({"row": e.id, "status": "skipped", "reason": reason}),
            None => json!({"row": e.id, "status": "case", "input": e.input, "cases": counts.get(&e.id).map_or(0, |m| m.values().sum::<usize>()), "classes": counts.get(&e.id)}),
        })
        .collect();
    json!({"schema": COVERAGE_SCHEMA, "app": report.app, "rows": rows})
}

/// `mimic-corpus/1`, one case per line so a change to one input is one line of the diff.
pub fn corpus_text(report: &Report) -> String {
    let spec = CorpusSpec {
        schema: CORPUS_SCHEMA.into(),
        seed: 0,
        generators: vec![GeneratorSpec::Corpus { name: format!("{}-api", report.app), op: Some("script".into()), files: vec![], cases: vec![] }],
    };
    let mut head = serde_json::to_value(&spec).expect("a spec prints");
    let lines: Vec<String> = report.cases.iter().map(|c| serde_json::to_string(c).expect("a case prints")).collect();
    head["generators"][0]["cases"] = json!([]);
    let open = serde_json::to_string_pretty(&head).expect("prints");
    // `"cases": []` becomes the case lines, in place
    let body = if lines.is_empty() { "[]".to_string() } else { format!("[\n      {}\n    ]", lines.join(",\n      ")) };
    open.replacen("\"cases\": []", &format!("\"cases\": {body}"), 1) + "\n"
}

pub fn outputs(report: &Report) -> Outputs {
    Outputs { inventory: pretty(&inventory(report)), corpus: corpus_text(report), coverage: pretty(&coverage(report)) }
}

/// The report the committed `inventory.json` and `corpus.json` stand for: the offline check runs the same guard over it.
pub fn from_files(inventory_text: &str, corpus_text: &str) -> Result<Report, String> {
    let inv: Value = serde_json::from_str(inventory_text).map_err(|e| format!("inventory.json is not JSON: {e}"))?;
    if inv.get("schema").and_then(Value::as_str) != Some(INVENTORY_SCHEMA) {
        return Err(format!("inventory.json is not {INVENTORY_SCHEMA}"));
    }
    let spec: CorpusSpec = serde_json::from_str(corpus_text).map_err(|e| format!("corpus.json is not {CORPUS_SCHEMA}: {e}"))?;
    let cases = spec.generators.into_iter().flat_map(|g| if let GeneratorSpec::Corpus { cases, .. } = g { cases } else { vec![] }).collect();
    let field = |k: &str| inv.get(k).cloned().ok_or_else(|| format!("inventory.json has no {k}"));
    let parse = |k: &str| -> Result<Value, String> { field(k) };
    Ok(Report {
        schema: REPORT_SCHEMA.into(),
        app: inv.get("app").and_then(Value::as_str).ok_or("inventory.json has no app")?.to_string(),
        pin: serde_json::from_value(parse("pin")?).map_err(|e| format!("inventory.json pin: {e}"))?,
        sources: serde_json::from_value(parse("sources")?).map_err(|e| format!("inventory.json sources: {e}"))?,
        endpoints: serde_json::from_value(parse("endpoints")?).map_err(|e| format!("inventory.json endpoints: {e}"))?,
        cli_commands: serde_json::from_value(parse("cli_commands")?).map_err(|e| format!("inventory.json cli_commands: {e}"))?,
        cases,
        blind: serde_json::from_value(parse("blind")?).map_err(|e| format!("inventory.json blind: {e}"))?,
    })
}

/// What one crawl produced: the report, its three files, the summary and what the guard found.
#[derive(Debug)]
pub struct Crawled {
    pub report: Report,
    pub outputs: Outputs,
    pub summary: Summary,
    pub problems: Vec<Problem>,
    pub warnings: Vec<String>,
}

pub fn crawl(crawler: &mut dyn Crawler, catalog: Option<&Catalog>, pin_commit: Option<&str>) -> Result<Crawled, CrawlError> {
    let report = crawler.crawl()?;
    let (problems, warnings) = check(&report, catalog, pin_commit);
    Ok(Crawled { outputs: outputs(&report), summary: summary(&report), report, problems, warnings })
}
